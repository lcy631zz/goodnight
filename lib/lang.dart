class Lang {
  static String locale = 'zh-CN';
  static bool _loaded = false;

  static Future<void> load() async {
    if (_loaded) return;
    try {
      final sp = await SharedPreferences.getInstance();
      final v = sp.getString('lang');
      if (v == 'zh-CN' || v == 'zh-TW') locale = v!;
    } catch (_) {
      locale = 'zh-CN';
    }
    _loaded = true;
  }

  static Future<void> set(String l) async {
    locale = l;
    try {
      final sp = await SharedPreferences.getInstance();
      await sp.setString('lang', l);
    } catch (_) {}
  }
}

/// 取当前语言下的文案；简体短语缺省为自身。
String t(String s) => Lang.locale == 'zh-TW' ? (_tw[s] ?? s) : s;
